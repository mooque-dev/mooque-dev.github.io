"""Build the sample reports used by the page's demo mode.

Everything here is made up: the café, the numbers and the dates. The layout copies
the shape of real Volante / Orbit reports closely enough for the page to read them.

Run:  python3 make_demo_pdfs.py   (writes the PDFs and ../demo.js next to this file)
"""
import base64
import pathlib

HERE = pathlib.Path(__file__).parent
STORE = "00000-Demo Cafe"
BANNER = "DEMO - SAMPLE DATA - NOT REAL"


def pdf(lines):
    """lines: list of (x, y, size, text). Returns bytes of a one-page landscape PDF."""
    esc = lambda s: s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    body = "".join(f"BT /F1 {sz} Tf 1 0 0 1 {x} {y} Tm ({esc(t)}) Tj ET\n" for x, y, sz, t in lines)
    objs = [
        "<</Type/Catalog/Pages 2 0 R>>",
        "<</Type/Pages/Kids[3 0 R]/Count 1>>",
        "<</Type/Page/Parent 2 0 R/MediaBox[0 0 792 612]/Contents 4 0 R/Resources<</Font<</F1 5 0 R>>>>>>",
        f"<</Length {len(body)}>>stream\n{body}endstream",
        "<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>",
    ]
    out, offsets = b"%PDF-1.4\n", []
    for i, o in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n{o}\nendobj\n".encode("latin-1")
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += "".join(f"{o:010d} 00000 n \n" for o in offsets).encode()
    out += f"trailer\n<</Size {len(objs) + 1}/Root 1 0 R>>\nstartxref\n{xref}\n%%EOF\n".encode()
    return out


def header(title, range_text):
    return [(36, 570, 11, f"{STORE}   {title}"), (36, 554, 9, range_text), (520, 570, 11, BANNER)]


def lunch_report(range_text, items):
    """items: (menu item, price, net qty). Columns follow Volante's Sales Report Summary."""
    cols = ["Gross", "VoidQty", "VoidAmt", "RefundQty", "RefundAmt", "OptionAmt", "Discount", "PriceLevelAdj", "Approx.Tax", "NetQty", "NetSales"]
    xs = [250 + i * 48 for i in range(len(cols))]
    lines = header("Sales Report Summary Grouped by Categories and Menu Items", range_text)
    y = 520
    lines += [(36, y, 8, "Category"), (110, y, 8, "MenuItem")] + [(x, y, 8, c) for x, c in zip(xs, cols)]
    y -= 18
    for i, (name, price, qty) in enumerate(items):
        net = price * qty
        vals = [net, 0, 0, 0, 0, 0, 0, 0, round(net * 0.13, 2), qty, net]
        if i == 0:
            lines.append((36, y, 8, "CustomLunch"))
        lines.append((110, y, 8, name))
        lines += [(x, y, 8, f"{v:.2f}") for x, v in zip(xs, vals)]
        y -= 14
    total_qty = sum(q for _, _, q in items)
    total = sum(p * q for _, p, q in items)
    lines += [(36, y, 8, "CustomLunch"), (110, y, 8, "---"), (xs[0], y, 8, f"{total:.2f}"), (xs[9], y, 8, f"{total_qty:.2f}"), (xs[10], y, 8, f"{total:.2f}")]
    return pdf(lines)


def orbit_report(range_text, rows):
    lines = header("Close Day Report", range_text)
    y = 520
    for label, *vals in rows:
        lines.append((36, y, 9, label))
        for i, v in enumerate(vals):
            lines.append((260 + i * 70, y, 9, v))
        y -= 15
    return pdf(lines)


LUNCH = lambda kl, km, il, im, veg, box, side: [
    ("BoxedLunch", 4.25, box), ("InternationalLunch", 4.25, il), ("InternationalMainDish", 3.49, im),
    ("KoreanLunch", 4.25, kl), ("KoreanMainDish", 3.49, km), ("SideDish", 1.49, side), ("VegetarianLunch", 4.25, veg),
]

files = {
    "Demo - Night report (Mon, Nov 2).pdf": lunch_report(
        "Mon, Nov 2 , 2026, 1:01PM -- Mon, Nov 2 , 2026, 11:00PM", LUNCH(3, 2, 28, 5, 4, 12, 9)),
    "Demo - Morning report (Tue, Nov 3).pdf": lunch_report(
        "Mon, Nov 2 , 2026, 11:00PM -- Tue, Nov 3 , 2026, 1:00PM", LUNCH(6, 3, 18, 7, 2, 9, 5)),
    # Sums are consistent: taxes add up to TAX, payments add up to net sales + tax.
    "Demo - Orbit close-day (Tue, Nov 3).pdf": orbit_report(
        "Mon, Nov 2 , 2026, 11:00PM -- Tue, Nov 3 , 2026, 10:59PM", [
            ("Z Counter", "1024"),
            ("CurrentReading(ZTotal)", "1002331.27"),
            ("PreviousReading", "1000000.00"),
            ("NetSales", "2050.00"),
            ("Cashier Voids+ Removes", "44.47"),
            ("TAX", "236.80"),
            ("Cash", "15.40"),
            ("AMEX", "98.25"),
            ("VISA", "1210.60"),
            ("Debit", "352.15"),
            ("MASTER", "585.90"),
            ("ZipthruRedemption", "24.50"),
            ("TransactionCount", "498.00"),
            ("GST", "490", "99.10"),
            ("HST8%C(ON)", "64", "12.40"),
            ("HST8%F(ON)", "430", "125.30"),
        ]),
}

for name, data in files.items():
    (HERE / name).write_bytes(data)

# demo.js: the same PDFs embedded, so demo mode works without any network request.
js = "// Generated by demo/make_demo_pdfs.py. Made-up sample reports for demo mode.\nconst DEMO_PDFS = [\n"
js += "".join(f'  ["{n}", "{base64.b64encode(d).decode()}"],\n' for n, d in files.items())
js += "];\n"
(HERE.parent / "demo.js").write_text(js)
print("wrote", len(files), "PDFs and demo.js")
